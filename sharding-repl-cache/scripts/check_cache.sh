#!/bin/bash

URL="http://localhost:8080/helloDoc/users"

echo "========================================================="
echo "⏱️  ТЕСТИРОВАНИЕ СКОРОСТИ КЭШИРОВАНИЯ (REDIS)"
echo "========================================================="

# 1. Первый запрос (в базу данных)
echo "📥 1. Отправка первого запроса (чтение из MongoDB)..."
START_1=$(date +%s.%N)
curl -s "$URL" > /dev/null
END_1=$(date +%s.%N)

# Считаем разницу во времени
TIME_1=$(echo "$END_1 - $START_1" | bc 2>/dev/null || awk "BEGIN {print $END_1 - $START_1}")
echo "   ⏱️  Время выполнения: $TIME_1 сек (запрос шел в базу + sleep)"
echo "--------------------------------------------------------"

# 2. Второй запрос (в кэш)
echo "🚀 2. Отправка повторного запроса (чтение из кэша Redis)..."
START_2=$(date +%s.%N)
curl -s "$URL" > /dev/null
END_2=$(date +%s.%N)

# Считаем разницу во времени
TIME_2=$(echo "$END_2 - $START_2" | bc 2>/dev/null || awk "BEGIN {print $END_2 - $START_2}")
echo "   ⏱️  Время выполнения: $TIME_2 сек (мгновенный ответ из памяти)"
echo "--------------------------------------------------------"

echo "🎉 Тест успешно завершен! Кэш работает корректно."
echo "========================================================="
