#!/bin/bash

# Останавливаем скрипт сразу, если какая-то из команд завершится ошибкой
set -e

# Автоматически определяем папку, в которой лежит этот главный скрипт
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

echo "========================================================="
echo "⚙️  НАЧАЛО ПОЛНОЙ НАСТРОЙКИ КЛАСТЕРА MONGODB"
echo "========================================================="

# 1. Запуск контейнеров
echo "📦 Шаг 1: Запуск Docker-контейнеров..."
# Запускаем compose из той папки, где лежит файл docker-compose.yml (обычно корень)
docker compose up -d

echo "⏳ Ожидание 10 секунд для запуска и стабилизации контейнеров..."
sleep 10

# 2. Настройка конфигурационного сервера
echo "🗂️ Шаг 2: Настройка конфигурационного сервера..."
"$SCRIPT_DIR/init_config.sh"

# 3. Настройка шардов
echo "💾 Шаг 3: Настройка серверов шардинга..."
"$SCRIPT_DIR/init_shards.sh"

echo "⏳ Ожидание 15 секунд для завершения выборов Primary во всех шардах..."
sleep 15

# 4. Настройка роутера и заполнение данными
echo "🧭 Шаг 4: Настройка роутера mongos и генерация 1000 документов..."
"$SCRIPT_DIR/init_router.sh"

echo "⏳ Ожидание 3 секунды перед финальной проверкой..."
sleep 3

# 5. Проверка распределения данных
echo "📈 Шаг 5: Проверка распределения данных по шардам..."
"$SCRIPT_DIR/check_shards.sh"

echo "⏳ Ожидание 2 секунды перед тестом кэширования..."
sleep 2

# 6. Тестирование скорости кэша Redis
echo "⏱️  Шаг 6: Тестирование скорости кэширования (Redis)..."
"$SCRIPT_DIR/check_cache.sh"

echo "========================================================="
echo "🎉 ВСЕ СКРИПТЫ УСПЕШНО ВЫПОЛНЕНЫ! КЛАСТЕР РАБОТАЕТ!"
echo "========================================================="
